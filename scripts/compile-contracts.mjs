// Compiles contracts/*.sol with solc-js (no native toolchain needed) and
// writes ABI + bytecode to src/adapters/evm/generated/ for the EVM adapter.
import { readFileSync, writeFileSync, mkdirSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import solc from 'solc';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const contractsDir = join(root, 'contracts');
const outDir = join(root, 'src/adapters/evm/generated');

const sources = Object.fromEntries(
  readdirSync(contractsDir)
    .filter((f) => f.endsWith('.sol'))
    .map((f) => [f, { content: readFileSync(join(contractsDir, f), 'utf8') }]),
);

const output = JSON.parse(
  solc.compile(
    JSON.stringify({
      language: 'Solidity',
      sources,
      settings: {
        optimizer: { enabled: true, runs: 200 },
        evmVersion: 'paris',
        outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object'] } },
      },
    }),
  ),
);

const errors = (output.errors ?? []).filter((e) => e.severity === 'error');
for (const e of output.errors ?? []) console[e.severity === 'error' ? 'error' : 'warn'](e.formattedMessage);
if (errors.length) process.exit(1);

mkdirSync(outDir, { recursive: true });
for (const [file, contracts] of Object.entries(output.contracts)) {
  for (const [name, artifact] of Object.entries(contracts)) {
    const ts =
      `// Generated by scripts/compile-contracts.mjs from contracts/${file}. Do not edit.\n` +
      `export const ${name}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;\n\n` +
      `export const ${name}Bytecode = '0x${artifact.evm.bytecode.object}' as const;\n`;
    writeFileSync(join(outDir, `${name}.ts`), ts);
    console.log(`compiled ${name} (${artifact.evm.bytecode.object.length / 2} bytes)`);
  }
}
